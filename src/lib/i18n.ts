const DICTS: Record<Lang, Partial<Record<DictKey, string>>> = { en: EN, sw: SW };

/** Translation hook — returns t(key) for the active language with EN fallback. */
export function useT() {
  const lang = useKeja((s) => s.lang);
  return (key: DictKey): string => DICTS[lang][key] ?? EN[key];
}
